import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openDatabase } from '../src/db/database.ts';
import { SupplierRepository } from '../src/features/suppliers/supplier.repository.ts';
import { OrderRepository } from '../src/features/orders/order.repository.ts';
import { WaitingRepository } from '../src/features/waiting/waiting.repository.ts';

test('receives, returns and cancels atomically with isolated traceable history', () => {
  const dir = mkdtempSync(join(tmpdir(), 'waiting-test-'));
  const path = join(dir, 'test.sqlite');
  let db = openDatabase(path);
  try {
    const suppliers = new SupplierRepository(db);
    const a = suppliers.create({ name: 'A' });
    const b = suppliers.create({ name: 'B' });
    let orders = new OrderRepository(db);
    let waiting = new WaitingRepository(db);
    orders.append(a.id, ['receive', 'return', 'cancel', 'stay']);
    orders.append(b.id, ['other']);
    const aid = orders.list(a.id).map((item) => item.id);
    const bid = orders.list(b.id).map((item) => item.id);
    orders.confirm(a.id, aid, aid);
    orders.confirm(b.id, bid, bid);
    const original = waiting.list(a.id);
    assert.throws(() => waiting.transition(a.id, [bid[0]!], aid, 'received'));
    assert.throws(() => waiting.transition(a.id, [aid[0]!, aid[0]!], aid, 'received'));
    db.exec("CREATE TRIGGER fail_history BEFORE INSERT ON item_history WHEN NEW.text = 'return' BEGIN SELECT RAISE(ABORT, 'fail'); END");
    assert.throws(() => waiting.transition(a.id, [aid[0]!, aid[1]!], aid, 'returned'));
    assert.equal(waiting.list(a.id).length, 4);
    assert.equal(orders.list(a.id).length, 0);
    assert.equal(db.prepare('SELECT count(*) AS n FROM item_history').get()?.n, 0);
    db.exec('DROP TRIGGER fail_history');
    waiting.transition(a.id, [aid[0]!], aid, 'received');
    assert.throws(() => waiting.transition(a.id, [aid[0]!], aid, 'received'));
    let ids = waiting.list(a.id).map((item) => item.id);
    waiting.transition(a.id, [aid[1]!], ids, 'returned');
    const returned = orders.list(a.id)[0]!;
    assert.notEqual(returned.id, aid[1]);
    assert.equal(returned.text, 'return');
    ids = waiting.list(a.id).map((item) => item.id);
    waiting.transition(a.id, [aid[2]!], ids, 'cancelled');
    assert.deepEqual(waiting.list(a.id).map((item) => item.text), ['stay']);
    assert.equal(waiting.list(b.id).length, 1);
    const history = db.prepare('SELECT * FROM item_history WHERE supplier_id = ? ORDER BY id').all(a.id);
    assert.deepEqual(history.map((row) => row.action), ['received', 'returned', 'cancelled']);
    assert.equal(history[1]!.returned_order_id, returned.id);
    assert.ok(history.every((row) => row.occurred_at && row.confirmed_at && row.created_at));
    assert.equal(history[0]!.confirmed_at, original[0]!.confirmedAt);
    orders.confirm(a.id, [returned.id], [returned.id]);
    assert.equal(waiting.list(a.id).length, 2);
    db.close();
    db = openDatabase(path);
    waiting = new WaitingRepository(db);
    assert.equal(waiting.list(a.id).length, 2);
    assert.equal(db.prepare('SELECT count(*) AS n FROM item_history').get()?.n, 3);
  } finally { db.close(); rmSync(dir, { recursive: true, force: true }); }
});
