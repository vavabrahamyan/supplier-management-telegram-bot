import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createBot } from '../src/bot/bot.ts';
import { loadConfig } from '../src/config/config.ts';
import { openDatabase } from '../src/db/database.ts';
import { SupplierRepository } from '../src/features/suppliers/supplier.repository.ts';
import { createLogger } from '../src/utils/logger.ts';

test('supplier menu creation, search, navigation, stale buttons and authorization', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'supplier-menu-'));
  const db = openDatabase(join(directory, 'test.sqlite'));
  const repo = new SupplierRepository(db);
  const bot = createBot(loadConfig({ BOT_TOKEN: 'fake', ALLOWED_TELEGRAM_USERNAMES: 'Alice' }), createLogger('error'), repo);
  bot.botInfo = { id: 1, is_bot: true, first_name: 'Test', username: 'test_bot', can_join_groups: false, can_read_all_group_messages: false, supports_inline_queries: false };
  const calls: { method: string; payload: any }[] = [];
  let messageId = 10;
  const prototype = Object.getPrototypeOf(bot.telegram) as typeof bot.telegram;
  const original = prototype.callApi;
  prototype.callApi = (async (method: string, payload: any) => { calls.push({ method, payload }); return method === 'sendMessage' ? { message_id: ++messageId } : true; }) as typeof bot.telegram.callApi;
  let updateId = 0;
  const from = (username = 'Alice') => ({ id: 7, is_bot: false, first_name: 'User', username });
  const chat = { id: 7, type: 'private' as const };
  const send = async (value: string, username = 'Alice') => bot.handleUpdate({ update_id: ++updateId, message: { message_id: updateId, date: 0, chat, from: from(username), text: value, ...(value.startsWith('/') ? { entities: [{ type: 'bot_command' as const, offset: 0, length: value.length }] } : {}) } });
  const click = async (data: string, id = messageId, username = 'Alice') => bot.handleUpdate({ update_id: ++updateId, callback_query: { id: String(updateId), from: from(username), chat_instance: 'x', message: { message_id: id, date: 0, chat }, data } });
  const latest = () => calls.filter((c) => c.method === 'sendMessage' || c.method === 'editMessageText').at(-1)!.payload;
  const button = (label: string) => latest().reply_markup.inline_keyboard.flat().find((b: any) => b.text === label)?.callback_data as string;
  try {
    await send('/start');
    assert.match(latest().text, /դեռ չկան/);
    assert.equal(button('🔎 Փնտրել մատակարար'), undefined);
    const oldSearch = button('➕ Ավելացնել մատակարար');
    const oldId = messageId;
    await click(oldSearch);
    assert.match(latest().text, /նոր մատակարարի/);
    await send('Alpha');
    assert.equal(repo.listActive().length, 1);
    assert.match(latest().text, /Alpha/);
    await send('/addsupplier');
    await send('alpha');
    assert.match(latest().text, /արդեն կա/);
    await send('/cancel');
    assert.ok(button('Alpha'));
    assert.ok(button('🔎 Փնտրել մատակարար'));
    assert.ok(button('➕ Ավելացնել մատակարար'));
    assert.equal(latest().reply_markup.inline_keyboard.at(-1).length, 2);
    await click(oldSearch, oldId);
    assert.equal(calls.at(-1)?.method, 'answerCallbackQuery');
    assert.match(calls.at(-1)?.payload.text, /ակտիվ չէ/);
    for (let i = 0; i < 7; i++) repo.create({ name: `Supplier ${i}` });
    await send('/new');
    const firstPage = button('➡️');
    assert.ok(firstPage);
    await click(firstPage);
    assert.ok(button('⬅️'));
    await click(button('⬅️'));
    await click(button('Alpha'));
    assert.match(latest().text, /Alpha/);
    await click(button('⬅️ Հետ'));
    await click(button('🔎 Փնտրել մատակարար'));
    await send('no match');
    assert.match(latest().text, /չեն գտնվել/);
    await click(button('➕ Ավելացնել մատակարար'));
    assert.match(latest().text, /նոր մատակարարի/);
    await send('New from search');
    assert.match(latest().text, /New from search/);
    await send('/start');
    await click(button('🔎 Փնտրել մատակարար'));
    await send('no match');
    await click(button('⬅️ Հետ'));
    await send('ALP');
    assert.ok(button('Alpha'));
    await click(button('Alpha'));
    await click(button('⬅️ Հետ'));
    assert.ok(button('Alpha'));
    await send('/addsupplier');
    await send('/start');
    await send('Should not create');
    assert.equal(repo.listActive().length, 9);
    const count = calls.length;
    await send('/addsupplier', 'Mallory');
    await click(oldSearch, oldId, 'Mallory');
    assert.equal(calls.length, count);
  } finally { prototype.callApi = original; db.close(); rmSync(directory, { recursive: true, force: true }); }
});
